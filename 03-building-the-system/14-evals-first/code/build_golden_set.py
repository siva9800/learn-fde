"""Day 14, step 1: choose, label and adjudicate the Godavari golden set; write the agreement report.

Run from the chapter folder (no network, no API key):

    python -X utf8 code/build_golden_set.py

Writes data/golden/ (manifest, both eval owners' labels, the adjudicated truth file, the adjudication log),
data/agreement-report.md and data/fewshot-examples.json (from the development split only).
"""

from __future__ import annotations

import json
import sys
from collections import Counter

from evals.agreement import agreement
from evals.golden import POOL_SIZE, bundle_sha256, day7_sample_ids, select
from evals.labels import ADJUDICATION_RULE, label_all
from evals.store import (ADJ_LOG, CHAPTER, FEWSHOT, LABELS_A, LABELS_B, MANIFEST, TRUTH, write_csv, write_jsonl,
                         write_text)


def main() -> int:
    test, dev = select()
    files = test + dev
    ls = label_all(files)
    out: list[str] = []

    def say(line: str = "") -> None:
        print(line)
        out.append(line)

    say("== Day 14 · the Godavari golden set ==")
    say(f"pool: one synthetic month from Day 7's generator ({POOL_SIZE} files, seed 14), two-wheeler and gold only")
    overlap = {f.file_id for f in files} & day7_sample_ids()
    say(f"golden files that are also in Day 7's 200-file development sample: {len(overlap)}")
    say(f"split: {len(test)} test (the golden set the harness scores) + {len(dev)} development "
        "(few-shot examples and tuning only)")
    for key in ("product", "branch", "channel", "language"):
        c = Counter(getattr(f, key) for f in test)
        say(f"  test by {key:9s}" + ", ".join(f"{k} {v}" for k, v in sorted(c.items())))
    say(f"  test files the analysts would send back: {sum(ls.final[f.file_id].send_back for f in test)}; "
        f"incomplete by the checklist: {sum(bool(ls.final[f.file_id].missing) for f in test)}")

    write_csv(MANIFEST, ["file_id", "split", "product", "branch", "channel", "language", "pages", "bundle_sha256"],
              [[f.file_id, f.split, f.product, f.branch, f.channel, f.language, len(ls.bundles[f.file_id].pages),
                bundle_sha256(ls.bundles[f.file_id])] for f in files])
    write_jsonl(LABELS_A, [{**ls.a[f.file_id].to_json(), "split": f.split} for f in files])
    write_jsonl(LABELS_B, [{**ls.b[f.file_id].to_json(), "split": f.split} for f in files])
    write_jsonl(TRUTH, [{**ls.final[f.file_id].to_json(), "split": f.split,
                         "bundle_sha256": bundle_sha256(ls.bundles[f.file_id])} for f in files])
    write_csv(ADJ_LOG, ["file_id", "item", "lakshmi", "senior_analyst", "final", "decided_by", "reason"],
              [[e.file_id, e.item, e.a, e.b, e.final, e.by, e.reason] for e in ls.log])

    say()
    say("-- inter-annotator agreement, test split (before adjudication) --")
    test_ls = type(ls)(test, ls.bundles, ls.paper, ls.a, ls.b, ls.final,
                       [e for e in ls.log if e.file_id in {f.file_id for f in test}])
    report = agreement(test_ls)
    for line in report.lines():
        say("  " + line if line else "")

    # Few-shot examples for the extraction prompt: development split only, and never more than three.
    examples = []
    for f in dev[:3]:
        fields = ls.final[f.file_id].fields
        examples.append({"file_id": f.file_id, "product": f.product,
                         "fields": {k: fields[k] for k in ("requested_amount", "tenure_months", "application_date")}})
    write_text(FEWSHOT, json.dumps({"split": "dev", "examples": examples}, indent=2, ensure_ascii=False))

    write_text(CHAPTER / "data" / "agreement-report.md",
               "# Godavari golden set · inter-annotator agreement\n\n> Generated by `code/build_golden_set.py`. "
               "Synthetic data. Do not edit by hand.\n\n## Adjudication rule\n\n```text\n" + ADJUDICATION_RULE +
               "\n```\n\n## Run\n\n```text\n" + "\n".join(out) + "\n```\n")
    say()
    say("wrote data/golden/manifest.csv, labels-lakshmi.jsonl, labels-senior-analyst.jsonl, "
        "truth-adjudicated.jsonl, adjudication-log.csv; data/agreement-report.md; data/fewshot-examples.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
