"""Day 14, step 3: calibrate a judge for the branch notes against the eval owners, then decide if it is trusted.

Run from the chapter folder (no network, no API key):

    python -X utf8 code/run_judge.py

Writes data/judge-calibration.json and data/judge-calibration.md.
"""

from __future__ import annotations

import json
import sys
from collections import Counter

from evals.golden import select
from evals.judge import RUBRIC, calibration, judge_v1_score, judge_v2, label_notes, make_notes
from evals.store import DATA, write_text


def main() -> int:
    test, dev = select()
    notes = make_notes(dev + test)
    label_notes(notes)
    result = calibration(notes)
    lines: list[str] = []

    def say(line: str = "") -> None:
        print(line)
        lines.append(line)

    say("== Day 14 · calibrating a judge for the branch notes ==")
    by = Counter((n.split, n.writer) for n in notes)
    say(f"notes: {result['notes']['dev']} development (calibration), {result['notes']['test']} test (held out); "
        + ", ".join(f"{s}/{w} {c}" for (s, w), c in sorted(by.items())))
    defects = Counter(d for n in notes if n.split == "test" for d in n.defects)
    say(f"defects really in the test notes: " + ", ".join(f"{k} {v}" for k, v in sorted(defects.items())))
    say(f"people failed {result['people_failed_test']} of {result['notes']['test']} test notes; "
        f"Lakshmi and the senior analyst agree with kappa {result['human_kappa_test']:.2f} (the ceiling for any judge)")
    say(f"judge v1 pass threshold chosen on the development notes: score >= {result['threshold_v1']:.1f}")
    say()
    say(f"{'judge':22s}{'split':>6s}{'n':>5s}{'agree':>8s}{'kappa':>7s}{'catches fails':>15s}"
        f"{'passes passes':>15s}{'probe own':>11s}{'probe other':>13s}{'judge right':>13s}")
    for name in ("judge-v1 (holistic)", "judge-v2 (rubric)"):
        for split in ("dev", "test"):
            s = result[name][split]
            say(f"{name:22s}{split:>6s}{s['n']:5d}{s['agreement']:8.1%}{s['kappa']:7.2f}{s['catches_fails']:15.1%}"
                f"{s['passes_passes']:15.1%}{s['own_family_pass']:11.0%}{s['other_pass']:13.0%}"
                f"{s['judge_right_people_wrong']:13d}")
    say("  probe own / probe other: pass rate on notes whose only defect is a missing citation, written by")
    say("  stub-model-v1 (the judge's own family) / by note-writer-b. Same defect; any gap is the judge's bias.")
    say("  judge right: disagreements with people where the hidden defects show the judge was the one right.")
    say()
    for name in ("judge-v1 (holistic)", "judge-v2 (rubric)"):
        say(f"{name}: {'TRUSTED in the gate' if result[name]['trusted_in_gate'] else 'advisory only, not in the gate'} "
            "(needs held-out kappa >= 0.80 and catches >= 90 percent of the notes people failed)")
    # Two examples the holistic judge got wrong, for the eval owners to read.
    wrong = [n for n in notes if n.split == "test" and not n.human_final and judge_v1_score(n) >= result["threshold_v1"]]
    say()
    say(f"notes people failed that judge v1 passed: {len(wrong)}; the first two, with judge v2's reasons:")
    for n in wrong[:2]:
        say(f"  {n.note_id} ({n.writer}; really: {', '.join(sorted(n.defects))})")
        for line in n.text.splitlines():
            say(f"    | {line}")
        say(f"    judge v2: {'; '.join(judge_v2(n)[1]) or 'pass'}")
    write_text(DATA / "judge-calibration.json", json.dumps(result, indent=2))
    write_text(DATA / "judge-calibration.md", "# Judge calibration · branch notes\n\n> Generated by "
               "`code/run_judge.py`. Synthetic data. Do not edit by hand.\n\n## Rubric\n\n```text\n" + RUBRIC +
               "\n```\n\n## Run\n\n```text\n" + "\n".join(lines) + "\n```\n")
    say()
    say("wrote data/judge-calibration.json and data/judge-calibration.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
