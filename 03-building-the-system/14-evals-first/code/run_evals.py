"""Day 14, step 2: run Day 11's pipeline over the golden set and report it per field and per stratum.

Run from the chapter folder after build_golden_set.py (no network, no API key):

    python -X utf8 code/run_evals.py                       # the baseline: Day 11's stub-model-v1
    python -X utf8 code/run_evals.py --candidate trimmed   # any candidate in evals/candidates.py

Refuses to run if a golden file's pages changed since labelling, or if the test split leaks into a prompt,
a few-shot example or Day 7's development sample. Writes data/eval-<candidate>.json (the summary),
data/eval-<candidate>-fields.jsonl (one row per field, for the gate), data/eval-report-<candidate>.md,
data/confident-wrong-<candidate>.md (full values, stays at Godavari) and
data/export-for-kaagaz-<candidate>.json (masked, for the product team).
"""

from __future__ import annotations

import argparse
import json
import sys

from evals import candidates, harness, hygiene
from evals.day11 import DAY11_CODE
from evals.golden import day7_sample_ids, select
from evals.store import CHAPTER, DATA, FEWSHOT, LABELS_A, LABELS_B, MANIFEST, load_truth, read_jsonl, read_manifest, \
    truth_sha256, write_jsonl, write_text
from intake.routing import threshold_for

LOADED_RUPEES_PER_HOUR = 456          # Day 9's loaded analyst cost
DAY12_RUPEES_PER_FILE = (6.34, 8.73)  # Day 12's measured night: p50 and p95 model cost per file
PROMPT_DIRS = [CHAPTER.parent / "12-llm-apis-for-production" / "code" / "prompts",
               CHAPTER.parent / "13-prompts-as-code" / "code" / "prompts",
               DAY11_CODE / "intake" / "model.py", DAY11_CODE / "intake" / "llm_adapter.py"]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--candidate", default="baseline", choices=["baseline", "rerun", "trimmed"])
    args = parser.parse_args(argv)
    lines: list[str] = []

    def say(line: str = "") -> None:
        print(line)
        lines.append(line)

    say(f"== Day 14 · golden-set eval: {args.candidate} ==")
    truth = load_truth()
    manifest = {r["file_id"]: r for r in read_manifest(MANIFEST)}
    test, _dev = select()
    if {f.file_id for f in test} != {k for k, r in manifest.items() if r["split"] == "test"}:
        say("REFUSED: the selection no longer matches the manifest; the golden set changed without a new version")
        return 2

    # Hygiene before scoring: the test split must not be anywhere the system can see it.
    corpora = hygiene.read_corpora([FEWSHOT, *PROMPT_DIRS])
    found = hygiene.leaks(truth, corpora)
    weak = hygiene.leaks(truth, corpora, weak=True)
    dev_overlap = hygiene.split_overlap(truth, {k for k, r in truth.items() if r["split"] == "dev"})
    day7_overlap = hygiene.split_overlap(truth, day7_sample_ids())
    say(f"hygiene: {len(corpora)} prompt and example files scanned, {len(found)} test-split values found in them; "
        f"{len(weak)} name or address matches for a person to look at; test files also in dev: {len(dev_overlap)}; "
        f"also in Day 7's development sample: {len(day7_overlap)}")
    if found or dev_overlap or day7_overlap:
        for corpus, fid, value in found[:10]:
            say(f"  LEAK {fid}: {value!r} in {corpus}")
        say("REFUSED: the golden set has leaked; scores would be inflated")
        return 3

    model = candidates.build(args.candidate)
    run = harness.run(model, test, truth, {k: r["bundle_sha256"] for k, r in manifest.items()})
    summary = harness.summarise(run)
    summary["truth_sha256"] = truth_sha256()
    say()
    for line in harness.report_lines(summary):
        say(line)

    # What the eval costs, and what the labels cost.
    a, b = read_jsonl(LABELS_A), read_jsonl(LABELS_B)
    label_hours = (sum(r["minutes"] for r in a) + sum(r["minutes"] for r in b)) / 60
    say()
    say("-- cost and cadence --")
    say(f"  this run: {summary['seconds']:.2f} s for {len(test)} files with the stub (offline, every pull request)")
    lo, hi = (len(test) * x for x in DAY12_RUPEES_PER_FILE)
    say(f"  the same run on a real model at Day 12's measured cost per file: about Rs {lo:,.0f} to Rs {hi:,.0f}")
    say(f"  labelling the {len(a)} files twice: {label_hours:.0f} analyst hours, about "
        f"Rs {label_hours * LOADED_RUPEES_PER_HOUR / 100000:.2f} lakh at Rs {LOADED_RUPEES_PER_HOUR} an hour")

    name = args.candidate
    DATA.mkdir(exist_ok=True)
    write_text(DATA / f"eval-{name}.json", json.dumps(summary, indent=2, ensure_ascii=False))
    write_jsonl(DATA / f"eval-{name}-fields.jsonl", harness.field_records(run))
    write_text(DATA / f"eval-report-{name}.md", f"# Golden-set eval · {name}\n\n> Generated by `code/run_evals.py`. "
               "Synthetic data. Do not edit by hand.\n\n```text\n" + "\n".join(lines) + "\n```\n")
    write_text(DATA / f"confident-wrong-{name}.md",
               f"# Confidently wrong fields · {name}\n\n> Generated by `code/run_evals.py`. Full values: this "
               "file stays inside Godavari's environment. Synthetic data.\n\n" +
               "\n".join(harness.confident_wrong_lines(run, threshold_for)))
    export = {"model": summary["model"], "as_of": summary["as_of"],
              "overall": {k: summary["overall"][k] for k in ("accuracy", "confident_wrong", "confident_wrong_rate",
                                                             "completeness_recall", "completeness_precision")},
              "confident_wrong": hygiene.export_rows(run.fields)}
    export_text = json.dumps(export, indent=2, ensure_ascii=False)
    hits = hygiene.pii_hits(export_text)
    if hits:
        say(f"REFUSED to write the export: {len(hits)} PII patterns found")
        return 4
    write_text(DATA / f"export-for-kaagaz-{name}.json", export_text)
    say()
    say(f"wrote data/eval-{name}.json, eval-{name}-fields.jsonl, eval-report-{name}.md, "
        f"confident-wrong-{name}.md, export-for-kaagaz-{name}.json (masked: 0 PII patterns)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
