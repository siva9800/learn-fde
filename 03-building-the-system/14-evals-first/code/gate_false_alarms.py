"""How often does the gate block a change that changed nothing, and how often does it catch the bad one?

Run from the chapter folder after run_evals.py (about 30 seconds; not for every pull request):

    python -X utf8 code/gate_false_alarms.py

Re-runs the unchanged model 30 times and the trimmed-prompt candidate 10 times against main's baseline,
under the stored policy and under a looser and a stricter one. Writes data/gate-false-alarms.md.
"""

from __future__ import annotations

import sys
from collections import Counter

from evals import candidates, gate, harness
from evals.golden import select
from evals.store import DATA, load_truth, read_jsonl, write_text

VARIANTS = {
    "stored policy": {},
    "looser: any net 3 regressions at p < 0.05, net new confident wrong > 1": {
        "min_net_regressions": 3, "paired_alpha": 0.05, "max_new_confident_wrong": 1},
    "average only: overall drop over 2 points": None,
}


def main() -> int:
    truth = load_truth()
    test, _ = select()
    policy = gate.load_policy()
    base_rows = read_jsonl(DATA / "eval-baseline-fields.jsonl")
    base = harness.summarise(harness.run(candidates.build("baseline"), test, truth))
    reruns = []
    for i in range(30):
        r = harness.run(candidates.build("rerun", f"rerun-{i}"), test, truth)
        reruns.append((harness.field_records(r), harness.summarise(r)))
    bad = []
    for i in range(10):
        r = harness.run(candidates.build("trimmed", f"candidate-{i}"), test, truth)
        bad.append((harness.field_records(r), harness.summarise(r)))
    lines = ["== Day 14 · the gate's own error rates ==",
             "30 re-runs of the unchanged model (should all pass) and 10 runs of the trimmed prompt (should all fail)", ""]
    for label, override in VARIANTS.items():
        def fails(rows: list, summary: dict) -> tuple[bool, list[str]]:
            if override is None:
                c = gate.average_only(base, summary, policy["average_only_max_drop_points"])
                return (not c.passed), ([] if c.passed else ["all"])
            checks = gate.compare(base_rows, rows, summary, {**policy, **override})
            failed = [f"{c.rule}:{c.stratum}" for c in checks if not c.passed]
            return bool(failed), failed
        fa = [fails(r, s) for r, s in reruns]
        det = [fails(r, s) for r, s in bad]
        why = Counter(x for f, w in fa if f for x in w)
        lines.append(f"{label}")
        lines.append(f"  false alarms on unchanged reruns: {sum(f for f, _ in fa)} of 30"
                     + (f" (most often: {', '.join(k for k, _ in why.most_common(3))})" if why else ""))
        lines.append(f"  trimmed prompt caught:            {sum(f for f, _ in det)} of 10")
    for line in lines:
        print(line)
    write_text(DATA / "gate-false-alarms.md", "# The gate's own error rates\n\n> Generated by "
               "`code/gate_false_alarms.py`. Synthetic data.\n\n```text\n" + "\n".join(lines) + "\n```\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
