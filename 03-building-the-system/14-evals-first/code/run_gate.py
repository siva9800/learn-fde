"""Day 14, step 4: the CI regression gate. Exit status 0 lets the change merge; 1 blocks it.

Run from the chapter folder after run_evals.py has written the baseline (data/eval-baseline*.json*):

    python -X utf8 code/run_gate.py --candidate rerun      # the same model run again: must pass
    python -X utf8 code/run_gate.py --candidate trimmed    # the trimmed prompt: must fail

In CI this runs on every pull request that touches a prompt, a model pin, chunking, retrieval or the
envelope; the baseline is the stored run from main, refreshed only when a change is accepted.
"""

from __future__ import annotations

import argparse
import json
import sys

from evals import candidates, gate, harness
from evals.golden import select
from evals.store import DATA, MANIFEST, load_truth, read_jsonl, read_manifest, truth_sha256, write_text



def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--candidate", required=True, choices=["baseline", "rerun", "trimmed"])
    args = parser.parse_args(argv)
    policy = gate.load_policy()
    lines: list[str] = []

    def say(line: str = "") -> None:
        print(line)
        lines.append(line)

    truth = load_truth()
    manifest = {r["file_id"]: r for r in read_manifest(MANIFEST)}
    sha = {k: r["bundle_sha256"] for k, r in manifest.items()}
    test, dev = select()
    base_rows = read_jsonl(DATA / "eval-baseline-fields.jsonl")
    base_summary = json.loads((DATA / "eval-baseline.json").read_text(encoding="utf-8"))

    say(f"== Day 14 · regression gate: {args.candidate} against main's baseline ==")
    say(f"policy {policy['version']}: bar {policy['registered_bar']['overall_field_accuracy_min']:.0%}, "
        f"completeness recall {policy['completeness_recall_min']:.0%}, fail a stratum on net regressions >= "
        f"{policy['min_net_regressions']} with p < {policy['paired_alpha']}, or net new confident wrong > "
        f"{policy['max_new_confident_wrong']}")

    # The noise floor, measured on the development split: the unchanged model, re-run five times.
    dev_base = harness.field_records(harness.run(candidates.build("baseline"), dev, truth, sha))
    floors = [gate.noise_floor(dev_base, harness.field_records(
        harness.run(candidates.build("rerun", f"rerun-{i}"), dev, truth, sha)), policy["strata"]) for i in range(5)]
    reg = max(f["max_net_regressions"] for f in floors)
    cw = max(f["max_net_new_confident_wrong"] for f in floors)
    above = reg < policy["min_net_regressions"] and cw <= policy["max_new_confident_wrong"]
    say(f"noise floor (dev split, unchanged model re-run 5 times): max net regressions {reg}, max net new "
        f"confident wrong {cw} in any stratum; thresholds {'sit above it' if above else 'ARE INSIDE THE NOISE'}")

    run = harness.run(candidates.build(args.candidate), test, truth, sha)
    cand_rows, cand_summary = harness.field_records(run), harness.summarise(run)
    cand_summary["truth_sha256"] = truth_sha256()
    checks = gate.compare(base_rows, cand_rows, cand_summary, policy, base_summary)
    avg = gate.average_only(base_summary, cand_summary, policy["average_only_max_drop_points"])
    failed = [c for c in checks if not c.passed]

    say()
    say(f"candidate: {cand_summary['model']}")
    say(f"  overall accuracy {base_summary['overall']['accuracy']:.1%} -> {cand_summary['overall']['accuracy']:.1%}; "
        f"confident wrong {base_summary['overall']['confident_wrong']} -> {cand_summary['overall']['confident_wrong']}; "
        f"fields flagged {base_summary['overall']['flagged_rate']:.1%} -> {cand_summary['overall']['flagged_rate']:.1%}")
    say(f"  an average-only gate (fail if overall drops more than {policy['average_only_max_drop_points']:.0f} "
        f"points) would say: {'PASS' if avg.passed else 'FAIL'} ({avg.detail})")
    say()
    say(f"{len(checks)} checks, {len(failed)} failed")
    for c in [c for c in checks if c.stratum == "all"]:
        say(f"  {'ok  ' if c.passed else 'FAIL'} {c.rule:20s} {c.stratum:30s} {c.detail}")
    for c in failed:
        if c.stratum != "all":
            say(f"  FAIL {c.rule:20s} {c.stratum:30s} {c.detail}")
    say()
    verdict = "BLOCKED: do not merge" if failed else "PASSED: may merge"
    say(f"verdict: {verdict}")
    write_text(DATA / f"gate-{args.candidate}.md", f"# Regression gate · {args.candidate}\n\n> Generated by "
               "`code/run_gate.py`. Synthetic data. Do not edit by hand.\n\n```text\n" + "\n".join(lines) + "\n```\n")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
