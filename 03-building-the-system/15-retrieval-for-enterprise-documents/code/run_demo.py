"""Day 15 project: permission-aware retrieval for Godavari's review queue, end to end, offline.

Run from the chapter's code/ folder (no network, no API key, no model download):

    python -X utf8 run_demo.py

It generates the synthetic corpus, chunks it two ways, builds the indexes, runs the analyst's panel query, the
post-filter leak, supersession, the PAN lookup, a branch transfer between two nightly group snapshots, the
40-query evaluation and the permission audit, and writes everything it prints to ../data/.
"""

from __future__ import annotations

import csv
import json
import time
from collections import Counter
from datetime import date, datetime
from pathlib import Path

from godavari_retrieval.chunking import chunk_corpus, clean_pages, learn_boilerplate
from godavari_retrieval.corpus import AS_OF, build_corpus
from godavari_retrieval.directory_data import SNAPSHOT_1, write_snapshots
from godavari_retrieval.evaluate import KS, answered_at, permission_audit, run_eval, scope_filter, summarise
from godavari_retrieval.permissions import POLICY_TYPES, Directory, SearchFilter, StaleDirectoryError, may_see
from godavari_retrieval.queries import QUERIES
from godavari_retrieval.service import NaivePostFilterService, Response, RetrievalService
from godavari_retrieval.text import PAN_RE, lexical_terms, naive_terms

CHAPTER = Path(__file__).resolve().parent.parent
DATA = CHAPTER / "data"
NOW = datetime(2026, 11, 25, 11, 0)          # Wednesday of week 5, 11 a.m., Lakshmi at her desk in Vijayawada
POLICY = SearchFilter(as_of=AS_OF, doc_types=POLICY_TYPES)
PRECEDENT = SearchFilter(as_of=AS_OF, doc_types=frozenset({"loan_decision"}))
HEADLINE = "what income proof is acceptable for a self-employed two-wheeler applicant in Guntur"
PRECEDENT_Q = ("similar past files: self-employed kirana shop two-wheeler, bank statement income, "
               "rent agreement with landlord electricity bill")


def main() -> int:
    started = time.perf_counter()
    out: list[str] = []

    def say(line: str = "") -> None:
        print(line)
        out.append(line)

    def show(resp: Response, label: str) -> None:
        say(f"  {label}: {len(resp.results)} shown, {resp.total_matches} matches counted")
        for n in resp.notices:
            say(f"    notice: {n}")
        for r in resp.results:
            say(f"    {r.rank}. {r.citation}")

    DATA.mkdir(exist_ok=True)
    say("== Day 15 · retrieval for Godavari's review queue: policy and precedent lookup ==")
    say(f"as of {AS_OF:%A %d %B %Y}; everything synthetic; standard library only")

    # 1. corpus -------------------------------------------------------------------------------------------
    docs, pans = build_corpus()
    kinds = Counter(d.doc_type for d in docs)
    circ = [d for d in docs if d.doc_type == "circular" and d.approval_status == "approved"]
    say("\n-- 1. The corpus (generated by code) --")
    say(f"documents: {len(docs)} = " + ", ".join(f"{k} {v}" for k, v in sorted(kinds.items())))
    say(f"approved circulars: {len(circ)} in {len({d.series for d in circ})} series; "
        f"{sum(1 for d in circ if d.superseded_by)} superseded; drafts: "
        f"{sum(1 for d in docs if d.approval_status == 'draft')}")
    say("loan decisions per branch: " + ", ".join(f"{b} {n}" for b, n in Counter(d.branch for d in docs if d.branch).items()))
    say("languages: " + ", ".join(f"{k} {v}" for k, v in sorted(Counter(d.language for d in docs).items())))
    say(f"scanned (OCR noise, stamp, hyphenation): {sum(d.scanned for d in docs)}; pages: {sum(len(d.pages) for d in docs)}")
    with (DATA / "corpus-manifest.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(["doc_id", "doc_type", "title", "product", "language", "effective_from", "effective_to",
                    "superseded_by", "approval_status", "branch", "pages", "scanned"])
        for d in docs:
            w.writerow([d.doc_id, d.doc_type, d.title, d.product, d.language, d.effective_from, d.effective_to or "",
                        d.superseded_by or "", d.approval_status, d.branch or "", len(d.pages), d.scanned])
    sample = next(d for d in docs if d.doc_id == "GFL/CO/2025/027")
    (DATA / "sample-pages-GFL-CO-2025-027.txt").write_text(
        "\n".join(f"===== page {i} =====\n" + "\n".join(p) for i, p in enumerate(sample.pages, start=1)) + "\n",
        encoding="utf-8", newline="\n")

    # 2. chunking -----------------------------------------------------------------------------------------
    structure, naive = chunk_corpus(docs), chunk_corpus(docs, "naive")
    bp = learn_boilerplate(docs)
    stats: Counter[str] = Counter()
    for d in docs:
        stats.update(clean_pages(d, bp)[1])
    say("\n-- 2. Chunking --")
    say(f"boilerplate learned from repetition: {len(bp)} line patterns; removed {stats['boilerplate']} lines, "
        f"{stats['junk']} junk lines, re-joined {stats['dehyphenated']} hyphenated words")
    say(f"structure-aware chunks: {len(structure)} (" + ", ".join(f"{k} {v}" for k, v in sorted(Counter(c.kind for c in structure).items())) + ")")
    say(f"naive 80-word windows: {len(naive)}")
    table = next(c for c in structure if c.doc_id == "GFL/CO/2025/027" and c.clause == "4.2")
    say(f"the income-proof table (clause 4.2) crosses pages {table.page_start} to {table.page_end}; "
        f"its first row group as one chunk:")
    for line in table.text.splitlines()[:4]:
        say(f"    {line[:110]}")
    bad = next(c for c in naive if c.doc_id == "GFL/CO/2025/027" and "Page 2 of 3" in c.text)
    say("a naive window over the same page break: ..." + bad.text[bad.text.index("Page 2 of 3") - 60:][:170] + "...")
    say(f"Telugu, two tokenizers: naive \\w+ gives {naive_terms('ఆదాయ రుజువు')}; "
        f"the lexical analyzer gives {lexical_terms('ఆదాయ రుజువు')}")

    # 3. the analyst's panel --------------------------------------------------------------------------------
    paths = write_snapshots(DATA)
    day1, day2 = Directory.load(paths[0]), Directory.load(paths[1])
    t0 = time.perf_counter()
    svc = RetrievalService(structure, day1)
    build_s = time.perf_counter() - t0
    say("\n-- 3. The panel in the review queue: Lakshmi, Guntur pilot file, two-wheeler, self-employed --")
    say(f"indexes built in {build_s:.2f} s (BM25 and the dense stand-in over {len(structure)} chunks)")
    t0 = time.perf_counter()
    pol = svc.search("lakshmi", HEADLINE, NOW, k=3, f=POLICY)
    pre = svc.search("lakshmi", PRECEDENT_Q, NOW, k=3, f=PRECEDENT)
    say(f"query: {HEADLINE!r} (two searches in {1000 * (time.perf_counter() - t0):.0f} ms)")
    show(pol, "Policy")
    show(pre, "Similar past files (your branches only)")
    say(f"  note drafted from the shown results only: {pre.note[:160]}...")

    # 4. the leak ---------------------------------------------------------------------------------------------
    say("\n-- 4. Post-filter against pre-filter: the same precedent query, as Lakshmi --")
    naive_svc = NaivePostFilterService(structure, day1)
    leak = naive_svc.search("lakshmi", PRECEDENT_Q, NOW, k=5, f=PRECEDENT)
    safe = svc.search("lakshmi", PRECEDENT_Q, NOW, k=5, f=PRECEDENT)
    principal = day1.resolve("lakshmi", NOW)
    hidden = [ln for ln in leak.debug_log if "GF-23562" in ln]
    say(f"  naive post-filter: {len(leak.results)} shown; banner '{leak.notices[-1]}'")
    say(f"    debug log line written before the filter: {hidden[0][:150] if hidden else '(none)'}")
    say(f"    panel note drafted before the filter mentions Kukatpally: {'Kukatpally' in leak.note}; "
        f"Sri Sai Motors: {'Sri Sai Motors' in leak.note}")
    say(f"    note: {leak.note[:220]}...")
    say(f"  pre-filter: {len(safe.results)} shown; {safe.total_matches} matches counted, all visible to her; "
        f"GF-23562 anywhere in the response: {'GF-23562' in json.dumps([safe.note, safe.debug_log, safe.keys()])}")
    invisible = sum(1 for r in safe.results if not may_see(principal, r.chunk))
    say(f"    results she may not see: {invisible}")
    sri = svc.search("srinivas", PRECEDENT_Q, NOW, k=3, f=PRECEDENT)
    say(f"  the same query as Srinivas (Hyderabad team): top result {sri.results[0].citation}")

    # 5. superseded and as-of ------------------------------------------------------------------------------
    say("\n-- 5. Superseded circulars and the version in force --")
    show(svc.search("lakshmi", "GFL/CO/2024/007 unmasked Aadhaar copy kept with consent", NOW, k=2, f=POLICY),
         "Lakshmi quotes the 2024 circular number")
    old_file = SearchFilter(as_of=date(2025, 3, 1), doc_types=POLICY_TYPES)
    show(svc.search("lakshmi", HEADLINE, NOW, k=2, f=old_file), "the same income question for a file decided on 1 March 2025")

    # 6. PAN ------------------------------------------------------------------------------------------------
    say("\n-- 6. PAN lookups through keyed tokens --")
    raw_in_index = sum(1 for c in structure if PAN_RE.search(c.text))
    say(f"  chunks containing a PAN-shaped string: {raw_in_index} (the index holds tokens only)")
    show(svc.search("lakshmi", "earlier files for PAN FGHPK1234J", NOW, k=3, f=PRECEDENT), "Lakshmi, a repeat customer's PAN")
    show(svc.search("lakshmi", "prior applications PAN GJKPM6650R", NOW, k=3, f=PRECEDENT), "Lakshmi, a PAN whose only file is in Warangal")
    show(svc.search("srinivas", "prior applications PAN GJKPM6650R", NOW, k=1, f=PRECEDENT), "Srinivas, the same PAN")
    say(f"  view log entry for that query: {json.dumps(svc.view_log[-1])}")

    # 7. groups change, the index does not ------------------------------------------------------------------
    say("\n-- 7. A transfer between two nightly snapshots; a stale snapshot; the service account --")
    q = "two-wheeler files approved this year"
    for directory, label in ((day1, "25 Nov snapshot"), (day2, "26 Nov snapshot")):
        s = RetrievalService(structure, directory)
        r = s.search("kkp.credit.officer", q, datetime(2026, 11, 26, 10, 0), k=3, f=PRECEDENT)
        say(f"  kkp.credit.officer, {label}: branches shown {sorted({x.chunk.meta.branch for x in r.results})}")
    try:
        svc.search("lakshmi", HEADLINE, datetime(2026, 11, 27, 9, 0), k=3, f=POLICY)
        say("  stale snapshot: answered (wrong)")
    except StaleDirectoryError as err:
        say(f"  27 Nov 09:00 with the 25 Nov snapshot: refused: {err}")
    show(svc.search("svc-kaagaz-retrieval", HEADLINE, NOW, k=3, f=POLICY), "the service account's own identity")
    show(svc.search("lakshmi", "video KYC for repeat customers", NOW, k=1, f=POLICY), "Lakshmi asks for the draft")
    show(svc.search("compliance.desk.01", "video KYC for repeat customers", NOW, k=1, f=POLICY), "the compliance desk asks")

    # 8. evaluation -----------------------------------------------------------------------------------------
    say("\n-- 8. Recall at k on 40 labelled queries (answer spans), as the user who asked --")
    configs = [("naive chunks, hybrid RRF", naive, "hybrid", False, 50),
               ("naive chunks, hybrid RRF + rerank top 50", naive, "hybrid", True, 50),
               ("structure, lexical (BM25) only", structure, "lexical", False, 50),
               ("structure, dense stand-in only", structure, "dense", False, 50),
               ("structure, hybrid RRF", structure, "hybrid", False, 50),
               ("structure, hybrid RRF + rerank top 20", structure, "hybrid", True, 20),
               ("structure, hybrid RRF + rerank top 50", structure, "hybrid", True, 50)]
    table_rows: list[str] = ["| Configuration | R@1 | R@3 | R@5 | R@10 | MRR |", "|---|---|---|---|---|---|"]
    final_rows = None
    say(f"  {'configuration':40} " + " ".join(f"R@{k:<4}" for k in KS) + " MRR")
    for label, chunks, mode, rr, top in configs:
        s = svc if (chunks is structure and mode == "hybrid" and rr and top == 50) else \
            RetrievalService(chunks, day1, mode, rr, top)
        rows = run_eval(s, NOW)
        sm = summarise(rows)["all"]
        say(f"  {label:40} " + " ".join(f"{sm[f'R@{k}']:.3f} " for k in KS) + f"{sm['MRR']:.3f}")
        table_rows.append(f"| {label} | " + " | ".join(f"{sm[f'R@{k}']:.3f}" for k in KS) + f" | {sm['MRR']:.3f} |")
        if s is svc:
            final_rows = rows
    assert final_rows is not None
    cats = summarise(final_rows)
    cat_lines = ["| Category | Queries | R@5 lexical | R@5 dense | R@5 final |", "|---|---|---|---|---|"]
    lex = summarise(run_eval(RetrievalService(structure, day1, "lexical", False), NOW))
    den = summarise(run_eval(RetrievalService(structure, day1, "dense", False), NOW))
    say("  by category, R@5:   lexical  dense  final")
    for c in sorted(k for k in cats if k != "all"):
        say(f"    {c:18} n={int(cats[c]['n']):<2}  {lex[c]['R@5']:.2f}     {den[c]['R@5']:.2f}   {cats[c]['R@5']:.2f}")
        cat_lines.append(f"| {c} | {int(cats[c]['n'])} | {lex[c]['R@5']:.2f} | {den[c]['R@5']:.2f} | {cats[c]['R@5']:.2f} |")
    hit, n, (lo, hi) = answered_at(final_rows, 5)
    say(f"  fully answered in the top 5: {hit} of {n}; 95 percent Wilson interval {lo:.2f} to {hi:.2f} "
        "(Day 14's stats.wilson, by path)")
    misses = [r for r in final_rows if r.recall[5] < 1]
    for r in misses:
        qq = next(x for x in QUERIES if x.qid == r.qid)
        say(f"  miss at 5: {r.qid} [{r.category}] {qq.text!r}; top 3 {r.top_ids[:3]}")
    users = ["lakshmi", "bhavani", "srinivas", "analyst.hyd.07", "kkp.credit.officer", "compliance.desk.01",
             "svc-kaagaz-retrieval"]
    checked, violations = permission_audit(svc, structure, day1, NOW, users)
    say(f"  permission audit (pre-filter): {checked} results checked for {len(users)} users x 40 queries x 2 scopes; "
        f"violations: {violations}")
    by_id = {c.chunk_id: c for c in structure}
    leaked = lines = 0
    for user in users[:5]:
        p = day1.resolve(user, NOW)
        for qq in QUERIES:
            r = naive_svc.search(user, qq.text, NOW, k=5, f=PRECEDENT)
            lines += len(r.debug_log)
            leaked += sum(1 for ln in r.debug_log if not may_see(p, by_id[ln.split()[2]]))
    say(f"  the naive post-filter, 5 analyst and branch users x 40 queries, precedent scope: {leaked} of {lines} "
        "debug-log lines (and the same files in the note's input) were files the user may not see")

    (DATA / "eval-report.md").write_text(
        "# Day 15 · retrieval evaluation (generated by code/run_demo.py)\n\n"
        f"40 labelled queries, answer-span labels, run as the asking user on {AS_OF:%d %B %Y}. Synthetic data.\n\n"
        + "\n".join(table_rows) + "\n\n" + "\n".join(cat_lines) + "\n\n"
        + f"Permission audit: {checked} results checked, {violations} violations.\n", encoding="utf-8", newline="\n")
    (DATA / "labelled-queries.json").write_text(json.dumps([q.__dict__ for q in QUERIES], ensure_ascii=False, indent=1)
                                                + "\n", encoding="utf-8", newline="\n")
    (DATA / "view-log.jsonl").write_text("".join(json.dumps(e, ensure_ascii=False) + "\n" for e in svc.view_log[:40]),
                                         encoding="utf-8", newline="\n")
    say(f"\nwrote data/: corpus-manifest.csv, sample-pages-GFL-CO-2025-027.txt, {paths[0].name}, {paths[1].name}, "
        "labelled-queries.json, eval-report.md, view-log.jsonl (first 40 entries), run-report.md")
    say(f"total run time {time.perf_counter() - started:.1f} s")
    (DATA / "run-report.md").write_text("# Day 15 · run report (output of code/run_demo.py)\n\n```text\n"
                                        + "\n".join(out) + "\n```\n", encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
