"""Day 13's whole story in one run: the prompt that works on page 1 and fails on page 40, the release
records, a prompt pull request that passes its gate and still regresses, the rollback, and model drift.

Run from code/:  python -X utf8 run_demo.py
Writes prompts/registry.json and the reports in ../data/. Deterministic: every run prints the same.
"""

from __future__ import annotations

import time
from pathlib import Path

from godavari_prompts import synth
from godavari_prompts.cli import diff_versions
from godavari_prompts.explain import explain
from godavari_prompts.fake_model import FakeProvider
from godavari_prompts.lint import lint
from godavari_prompts.loader import PROMPTS_DIR, content_hash, load, version_dir
from godavari_prompts.model_port import Tier
from godavari_prompts.pipeline import FileResult, ModelMismatch, resolve, run_batch
from godavari_prompts.regress import by_page_band, outcome, score, table
from godavari_prompts.registry import Registry, RegistryError, Release, release_id

DATA = Path(__file__).resolve().parent.parent / "data"
PINNED = {Tier.SMALL: "fake-small-2026-10", Tier.LARGE: "fake-large-2026-10"}
MODELS_1X = {"large": "fake-large-2026-10"}
MODELS_2X = {"small": "fake-small-2026-10", "large": "fake-large-2026-10"}
FDE, REVIEWER, PLATFORM, COMPLIANCE = "fde.kaagaz", "platform.kaagaz", "platform.kaagaz", "compliance-head.godavari"


def new_release(version: str, models: dict[str, str]) -> Release:
    pv = load("extraction", version)
    return Release(release_id("extraction", version, models), "extraction", version,
                   content_hash(version_dir("extraction", version)), models, pv.meta["output_schema"],
                   pv.meta["author"], pv.meta["created"], pv.meta["summary"])


def run(rel: Release, files: list[synth.LoanFile], provider: FakeProvider) -> list[FileResult]:
    return run_batch(rel, load(rel.prompt_id, rel.version, expected_sha256=rel.content_sha256), files, provider)


def count(results: list[FileResult], files: list[synth.LoanFile], fld: str, only: str | None = None) -> str:
    e = score(results, files, "x", only=only)["per_field"].get(fld)
    return f"{e['correct']}/{e['n']}" if e else "-"


def main() -> None:
    t0 = time.perf_counter()
    DATA.mkdir(exist_ok=True)
    provider = FakeProvider(PINNED, today="2026-11-12")
    report: list[str] = ["# Day 13 run report", "", "Generated by `code/run_demo.py`. Synthetic files, fake model.", ""]

    def say(line: str = "") -> None:
        print(line)
        report.append(line)

    # 1. Works on page 1 ----------------------------------------------------------------------------
    say("== 1. Works on page 1: extraction@1.0.0 on twelve 3-page demo samples ==")
    samples = synth.three_page_samples()
    r10 = new_release("1.0.0", MODELS_1X)
    e = score(run(r10, samples, provider), samples, "three-page-samples")
    say(f"fields correct {e['correct_rate']:.1%}, wrong {e['wrong_rate']:.1%}, "
        f"input tokens per file {e['input_tokens_per_file']['large']}")
    say()

    # 2. Fails on page 40 ---------------------------------------------------------------------------
    say("== 2. Fails on page 40: 50 synthetic 40-page files (30 Kukatpally, 20 Guntur) ==")
    lab = synth.lab_set()
    co_n = sum(f.truth["co_applicant_name"] != "none" for f in lab)
    te_n = sum(f.telugu_income for f in lab)
    say(f"{co_n} files have a co-applicant added at sanction (page 38); {te_n} have a handwritten Telugu income page")
    say(f"{'release':<38}{'correct':>8}{'wrong':>7}{'co-app':>8}{'Telugu inc':>11}{'calls':>7}{'small tok':>10}{'large tok':>10}")
    lab_runs: dict[str, list[FileResult]] = {}
    for version, models in (("1.0.0", MODELS_1X), ("1.1.0", MODELS_1X), ("2.0.0", MODELS_2X)):
        rel = new_release(version, models)
        res = run(rel, lab, provider)
        lab_runs[version] = res
        ev = score(res, lab, "lab-50")
        calls = sum(len(r.calls) for r in res) / len(res)
        say(f"{rel.release_id:<38}{ev['correct_rate']:>8.1%}{ev['wrong_rate']:>7.1%}"
            f"{count(res, lab, 'co_applicant_name', 'co_applicant'):>8}{count(res, lab, 'monthly_income', 'telugu_income'):>11}"
            f"{calls:>7.1f}{ev['input_tokens_per_file']['small']:>10}{ev['input_tokens_per_file']['large']:>10}")
    say()
    say("Fields read correctly, by where the answer is printed in the file:")
    bands = [(1, 2), (3, 12), (13, 24), (25, 35), (36, 40)]
    rows = {v: by_page_band(res, lab, bands) for v, res in lab_runs.items()}
    say(f"{'where':<14}{'fields':>7}" + "".join(f"{v:>10}" for v in rows))
    for i, (lo, hi) in enumerate(bands):
        n = rows["1.0.0"][i][1]
        say(f"{f'pages {lo}-{hi}':<14}{n:>7}" + "".join(f"{rows[v][i][2] / n:>10.0%}" for v in rows))
    say()
    say("extraction@1.0.0 on the 40-page files, per field (n = files that have the field):")
    for line in table(score(lab_runs["1.0.0"], lab, "lab-50")).splitlines():
        say("  " + line)
    say()
    f38 = next(f for f in lab if f.truth["co_applicant_name"] != "none"
               and lab_runs["1.0.0"][lab.index(f)].fields["co_applicant_name"]["value"] == "none")
    got = lab_runs["1.0.0"][lab.index(f38)].fields["co_applicant_name"]
    say(f"One of them: {f38.file_id} ({f38.product}, {f38.branch}). Page 38 names co-applicant {f38.truth['co_applicant_name']}.")
    say(f"  1.0.0 returned {got['value']!r} from page {got['page']} with confidence {got['confidence']}: the form, not the annexure.")
    v2 = lab_runs["2.0.0"][lab.index(f38)].fields["co_applicant_name"]
    say(f"  2.0.0 returned {v2['value']!r} from page {v2['page']} (page 38 classified {lab_runs['2.0.0'][lab.index(f38)].page_types[38]!r}).")
    say()

    # 3. Release records ----------------------------------------------------------------------------
    say("== 3. Release records: each version scored on the 12 labelled Kukatpally files ==")
    labelled = synth.labelled_set()
    reg = Registry()
    timeline = [("1.0.0", MODELS_1X, "2026-11-09T16:20", "first extraction prompt for the skeleton"),
                ("1.1.0", MODELS_1X, "2026-11-10T15:45", "repeat the request after the document"),
                ("2.0.0", MODELS_2X, "2026-11-11T17:10", "classify pages first; per-page templates")]
    for version, models, at, reason in timeline:
        rel = reg.add_release(new_release(version, models))
        reg.record_eval(rel.release_id, score(run(rel, labelled, provider), labelled, "kukatpally-labelled-12"))
        reg.approve(rel.release_id, REVIEWER)
        reg.promote("dev", rel.release_id, by=FDE, at=at, reason=reason)
    r20 = reg.releases[release_id("extraction", "2.0.0", MODELS_2X)]
    pv20 = load("extraction", "2.0.0", expected_sha256=r20.content_sha256)
    explained = explain(r20, pv20, "two-wheeler")
    (DATA / "what-the-system-is-told-2.0.0-two-wheeler.md").write_text(explained, encoding="utf-8", newline="\n")
    reg.compliance_read(r20.release_id, COMPLIANCE)
    reg.promote("pilot", r20.release_id, by=FDE, at="2026-11-11T18:30",
                reason="skeleton environment for the M07 demo; compliance head read the rendered prompts")
    say(f"{'release':<38}{'author':<16}{'approved by':<17}{'correct':>8}{'wrong':>7}{'large tok':>10}")
    for rel in reg.releases.values():
        say(f"{rel.release_id:<38}{rel.author:<16}{rel.approved_by or '-':<17}{rel.eval['correct_rate']:>8.1%}"
            f"{rel.eval['wrong_rate']:>7.1%}{rel.eval['input_tokens_per_file']['large']:>10}")
    say(f"pilot pins {reg.current('pilot', 'extraction').release_id}; "
        f"the compliance head read data/what-the-system-is-told-2.0.0-two-wheeler.md ({len(explained.split())} words)")
    say()

    # 4. A prompt pull request ----------------------------------------------------------------------
    say("== 4. Pull request: extraction 2.0.0 -> 2.1.0 (the platform engineer's token trim) ==")
    diff = diff_versions("extraction", "2.0.0", "2.1.0")
    (DATA / "diff-2.0.0-to-2.1.0.diff").write_text(diff, encoding="utf-8", newline="\n")
    added = sum(1 for ln in diff.splitlines() if ln.startswith("+") and not ln.startswith("+++"))
    removed = sum(1 for ln in diff.splitlines() if ln.startswith("-") and not ln.startswith("---"))
    files_touched = sum(1 for ln in diff.splitlines() if ln.startswith("+++ ") or ln.startswith("--- /dev"))
    say(f"diff: {files_touched} files, +{added} -{removed} lines (data/diff-2.0.0-to-2.1.0.diff)")
    for version in ("2.0.0", "2.1.0"):
        rep = lint(load("extraction", version))
        say(f"lint {rep.ref}: {len(rep.errors)} errors, {len(rep.warnings)} warnings"
            + "".join(f"\n  WARNING {w}" for w in rep.warnings))
    r21 = reg.add_release(new_release("2.1.0", MODELS_2X))
    reg.record_eval(r21.release_id, score(run(r21, labelled, provider), labelled, "kukatpally-labelled-12"))
    say(f"gate on the labelled set: 2.0.0 {r20.eval['correct_rate']:.1%} correct, {r20.eval['wrong_rate']:.1%} wrong, "
        f"{r20.eval['input_tokens_per_file']['large']} large tokens per file")
    say(f"                          2.1.0 {r21.eval['correct_rate']:.1%} correct, {r21.eval['wrong_rate']:.1%} wrong, "
        f"{r21.eval['input_tokens_per_file']['large']} large tokens per file")
    try:
        reg.approve(r21.release_id, PLATFORM)
    except RegistryError as exc:
        say(f"approve as the author: refused: {exc}")
    reg.approve(r21.release_id, FDE)
    reg.compliance_read(r21.release_id, COMPLIANCE)
    reg.promote("pilot", r21.release_id, by=FDE, at="2026-11-12T10:05", reason="token trim; gate passed")
    say(f"promoted: pilot pins {reg.current('pilot', 'extraction').release_id}")
    say()

    # 5. Rollback drill -----------------------------------------------------------------------------
    say("== 5. Rollback drill: replaying 20 recent Guntur files through what pilot runs ==")
    guntur = synth.guntur_replay()
    rel, pv = resolve(reg, "pilot")
    res = run_batch(rel, pv, guntur, provider)
    wrong = sum(outcome("monthly_income", r.fields["monthly_income"], f.truth["monthly_income"]) == "wrong"
                for r, f in zip(res, guntur))
    say(f"{rel.release_id}: monthly_income wrong on {wrong} of {len(guntur)} files "
        f"(Telugu declarations: {count(res, guntur, 'monthly_income', 'telugu_income')} correct)")
    bad = next(r for r, f in zip(res, guntur)
               if f.telugu_income and outcome("monthly_income", r.fields["monthly_income"], f.truth["monthly_income"]) == "wrong")
    truth = next(f for f in guntur if f.file_id == bad.file_id).truth["monthly_income"]
    say(f"  e.g. {bad.file_id}: read {bad.fields['monthly_income']['value']} as monthly; the declaration says {truth} a month")
    alert = wrong / len(guntur) > 0.10
    say(f"alert rule 'monthly_income wrong > 10% of the replay window': {'FIRES' if alert else 'quiet'}")
    started = time.perf_counter()
    restored = reg.rollback("pilot", "extraction", by=FDE, at="2026-11-12T11:40",
                            reason="Guntur replay: Telugu monthly income read as annual after 2.1.0")
    took_ms = (time.perf_counter() - started) * 1000
    say(f"rollback: pilot pins {restored} (one registry change, no deploy)")
    print(f"  (re-pin took {took_ms:.1f} ms on this machine)")
    affected = sorted({c.file_id for r in res for c in r.calls if c.release_id == r21.release_id})
    rel, pv = resolve(reg, "pilot")
    rerun = run_batch(rel, pv, [f for f in guntur if f.file_id in affected], provider)
    wrong_after = sum(outcome("monthly_income", r.fields["monthly_income"], f.truth["monthly_income"]) == "wrong"
                      for r, f in zip(rerun, [f for f in guntur if f.file_id in affected]))
    say(f"re-ran the {len(affected)} files processed under 2.1.0 (new idempotency keys): monthly_income wrong on {wrong_after}")
    reg.releases[r21.release_id].notes.append("rolled back in pilot 2026-11-12T11:40: Telugu monthly income read as "
                                              "annual on the Guntur replay; the labelled set has no Telugu declarations")
    try:
        reg.promote("pilot", r21.release_id, by=PLATFORM, at="2026-11-12T12:00", reason="try again")
    except RegistryError as exc:
        say("re-promote 2.1.0: " + str(exc).splitlines()[-1].strip("- ").strip())
    lab21 = run(r21, lab, provider)
    say(f"what the lab set would have said: Telugu income correct 2.0.0 {count(lab_runs['2.0.0'], lab, 'monthly_income', 'telugu_income')}, "
        f"2.1.0 {count(lab21, lab, 'monthly_income', 'telugu_income')}")
    say()

    # 6. Drift --------------------------------------------------------------------------------------
    say("== 6. Drift: the provider moves 'fake-large-latest' to a new snapshot on 16 November ==")
    aliased = FakeProvider({Tier.SMALL: "fake-small-2026-10", Tier.LARGE: "fake-large-latest"}, today="2026-11-17")
    current = reg.current("pilot", "extraction")
    try:
        run(current, labelled, aliased)
    except ModelMismatch as exc:
        say(f"adapter configured with the alias: {exc}")
    try:
        reg.add_release(Release(release_id("extraction", "2.0.0", {"large": "fake-large-latest"}), "extraction",
                                "2.0.0", current.content_sha256, {"large": "fake-large-latest"}, "", FDE, "", ""))
    except RegistryError as exc:
        say(f"release pinned to the alias: refused: {exc}")
    new_models = {"small": "fake-small-2026-10", "large": "fake-large-2026-11"}
    candidate = reg.add_release(new_release("2.0.0", new_models))
    drift_provider = FakeProvider({Tier.SMALL: "fake-small-2026-10", Tier.LARGE: "fake-large-2026-11"}, today="2026-11-17")
    reg.record_eval(candidate.release_id, score(run(candidate, labelled, drift_provider), labelled, "kukatpally-labelled-12"))
    reg.approve(candidate.release_id, REVIEWER)
    reg.compliance_read(candidate.release_id, COMPLIANCE)
    say(f"nightly drift check, same prompt on the new snapshot: {candidate.eval['correct_rate']:.1%} correct, "
        f"{candidate.eval['wrong_rate']:.1%} wrong (pinned: {current.eval['correct_rate']:.1%}, {current.eval['wrong_rate']:.1%})")
    try:
        reg.promote("pilot", candidate.release_id, by=FDE, at="2026-11-17T09:00", reason="adopt the new snapshot")
    except RegistryError as exc:
        say("promotion: " + str(exc).replace("\n", "\n  "))
    say()

    # 7. The registry ------------------------------------------------------------------------------
    say("== 7. The registry file ==")
    path = reg.save(PROMPTS_DIR / "registry.json")
    problems = Registry.load(path).verify()
    say(f"wrote prompts/registry.json: {len(reg.releases)} releases, {len(reg.history)} history events; "
        f"verify: {'clean' if not problems else problems}")
    for env, pins in reg.environments.items():
        say(f"  {env:<11}" + (", ".join(pins.values()) or "(nothing pinned until the January waves)"))
    say()
    say(f"run time {time.perf_counter() - t0:.1f} s")
    (DATA / "run-report.md").write_text("\n".join(report[:4]) + "\n```text\n" + "\n".join(report[4:-1]) + "\n```\n",
                                        encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
