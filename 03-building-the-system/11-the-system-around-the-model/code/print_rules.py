"""Print the rule sheet the compliance head reads and signs, generated from the rule code itself.

    python -X utf8 code/print_rules.py

Writes data/rules-sheet-two-wheeler.md and data/rules-sheet-gold.md and prints each ruleset's
fingerprint. The sheet is generated, never typed, so it cannot drift from what the code enforces. What
she signs is the sheet plus the fingerprint printed at its foot; the run refuses code that does not match.
"""

from __future__ import annotations

from pathlib import Path

from intake import rules_gold, rules_kyc, rules_two_wheeler
from intake.ruleset import RuleSet, load_signoff

DATA = Path(__file__).resolve().parent.parent / "data"


def sheet(ruleset: RuleSet) -> str:
    record = load_signoff().get(ruleset.product, {})
    lines = [
        f"# Completeness and product rules · {ruleset.product} · v{ruleset.version}",
        "",
        "> Generated by `code/print_rules.py` from the rule code. Synthetic Godavari policy for the course.",
        f"> Status: **{record.get('status', 'no record')}**. Fingerprint of the code: `{ruleset.fingerprint()}`",
        "",
        "| Rule | Kind | The rule | Source |",
        "|---|---|---|---|",
    ]
    for rule in ruleset.rules:
        lines.append(f"| {rule.rule_id} | {rule.kind.value} | {rule.text} | {rule.source} |")
    lines += ["", "**Address proofs accepted (signed list v0.3).** Officially valid documents: "
              + ", ".join(sorted(rules_kyc.OVD_ADDRESS_PROOFS)) + ". Alternatives:", ""]
    for kind, condition in rules_kyc.SIGNED_ALTERNATIVES.items():
        lines.append(f"- {kind}: {condition}")
    lines += ["", "Anything not listed is not accepted. Regulatory rules cannot be overridden; policy rules may be "
              "overridden by a named analyst with a written reason, which is logged.", "",
              "| Signed by | Date | Fingerprint |", "|---|---|---|",
              f"| {record.get('signed_by') or '(not yet signed)'} | {record.get('signed_on') or '-'} | "
              f"{record.get('fingerprint', '-')} |", ""]
    return "\n".join(lines)


def main() -> None:
    DATA.mkdir(exist_ok=True)
    for rs in (rules_two_wheeler.RULESET, rules_gold.RULESET):
        path = DATA / f"rules-sheet-{rs.product}.md"
        path.write_text(sheet(rs), encoding="utf-8", newline="\n")
        print(f"{rs.product:12s} v{rs.version}  {len(rs.rules):2d} rules  fingerprint {rs.fingerprint()}  -> {path.name}")


if __name__ == "__main__":
    main()
