"""Render the FDE lineage timeline from data/fde-timeline.csv as a Markdown table.

Standard library only. Run from the chapter folder:

    python -X utf8 code/timeline.py

Checks every row has a parseable date (YYYY, YYYY-MM or YYYY-MM-DD), a source and a
known source type, sorts by date, writes data/fde-timeline.md and prints a count of
rows per source type so you can see how much of the story rests on vendor and
recruiter content rather than primary or company sources.
"""

from __future__ import annotations

import csv
import re
import sys
from collections import Counter
from pathlib import Path

SOURCE_TYPES: set[str] = {"primary", "company", "vendor", "recruiter", "press", "job board"}
DATE_RE = re.compile(r"^\d{4}(-\d{2}){0,2}$")

CHAPTER = Path(__file__).resolve().parent.parent
CSV_PATH = CHAPTER / "data" / "fde-timeline.csv"
MD_PATH = CHAPTER / "data" / "fde-timeline.md"


def load_rows(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def check(rows: list[dict[str, str]]) -> list[str]:
    problems: list[str] = []
    for i, row in enumerate(rows, start=2):  # line 1 is the header
        if not DATE_RE.match(row["date"].strip()):
            problems.append(f"line {i}: date {row['date']!r} is not YYYY, YYYY-MM or YYYY-MM-DD")
        if not row["source"].strip():
            problems.append(f"line {i}: no source; a dated claim without a source is a rumour")
        if row["source_type"].strip() not in SOURCE_TYPES:
            problems.append(f"line {i}: source_type {row['source_type']!r} not in {sorted(SOURCE_TYPES)}")
    return problems


def render(rows: list[dict[str, str]]) -> str:
    lines = [
        "# The FDE lineage timeline (generated by code/timeline.py)",
        "",
        "| Date | Event | Who | Source | Type |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['date']} | {r['event']} | {r['who']} | {r['source']} | {r['source_type']} |"
        )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    rows = load_rows(CSV_PATH)
    problems = check(rows)
    if problems:
        print("problems (fix the CSV before trusting the table):")
        for p in problems:
            print("  -", p)
        return 1
    rows.sort(key=lambda r: r["date"])  # ISO-style strings sort correctly
    MD_PATH.write_text(render(rows), encoding="utf-8", newline="\n")
    counts = Counter(r["source_type"] for r in rows)
    print(f"{len(rows)} rows, {rows[0]['date']} to {rows[-1]['date']}, written to {MD_PATH.name}")
    print("rows per source type:")
    for kind, n in counts.most_common():
        print(f"  {kind:<10} {n}")
    soft = sum(counts[k] for k in ("vendor", "recruiter"))
    print(f"{soft} of {len(rows)} rows rest on vendor or recruiter content; quote them as such")
    return 0


if __name__ == "__main__":
    sys.exit(main())
