Key = tuple[str, str]


def allocate(strata: dict[Key, list], n: int, minimum: int) -> dict[Key, int]:
    """Proportional allocation with a floor, by largest remainder, never more than a stratum holds."""
    total = sum(len(v) for v in strata.values())
    alloc = {k: min(len(v), minimum) for k, v in strata.items()}
    quota = {k: len(v) * n / total for k, v in strata.items()}
    for k in strata:                                   # whole part of what is still owed
        owed = int(max(0.0, quota[k] - alloc[k]))
        alloc[k] += min(owed, len(strata[k]) - alloc[k])
    left = n - sum(alloc.values())
    order = sorted(strata, key=lambda k: quota[k] - alloc[k], reverse=True)
    i = 0
    while left > 0 and i < 10 * len(order):            # the rest by largest remainder
        k = order[i % len(order)]
        if alloc[k] < len(strata[k]):
            alloc[k] += 1
            left -= 1
        i += 1
    return alloc


@dataclass
class HandCount:
    """What the hand-count form records for one sampled file (section 03.6)."""

    file_id: str
    branch: str
    product: str
    channel: str
    stratum_size: int
    stratum_sampled: int
    turnaround_days: float      # signed at branch -> decision
    transit_days: float         # signed -> visible on SFTP
    queue_days: float           # visible -> first opened by an analyst (the tracker cannot see this)
    work_days: float            # first opened -> decision, batch included, branch wait excluded
    branch_wait_days: float     # waiting for the branch to resend
    analyst_hours: float
    rekey_hours: float
    completeness_hours: float
    chasing_hours: float
    assessment_hours: float
    sent_back: bool
    incomplete: bool
    slipped: bool               # incomplete and not sent back: decided with a mandatory document missing
    outcome: str                # sanctioned, rejected, withdrawn

    @property
    def weight(self) -> float:
        return self.stratum_size / self.stratum_sampled

    @property
    def addressable_hours(self) -> float:
        return self.rekey_hours + self.completeness_hours + self.chasing_hours


def clamp(x: float, lo: float, hi: float) -> float:
    return max(lo, min(hi, x))


def hand_count(f, size: int, sampled: int, rng: random.Random) -> HandCount:
    """Simulate the four timestamps, the timing log and the outcome for one file.

    Day 7's generator gives a total turnaround and total hours per file. A real hand count reads the
    split from the application form, the SFTP log, the tracker and the core; here it is simulated so
    that the parts add up exactly to the generator's totals.
    """
    transit = clamp(rng.gauss(1.1, 0.4), 0.3, 2.5)
    work = clamp(rng.gauss(1.5, 0.3), 0.8, 2.5)
    wait = clamp(rng.gauss(3.0, 0.8), 1.0, 6.0) if f.sent_back else 0.0
    queue = f.turnaround_days - transit - work - wait
    if queue < 0.2:                                    # a fast file: shrink the parts to fit the total
        scale = (f.turnaround_days - 0.2) / (transit + work + wait)
        transit, work, wait, queue = transit * scale, work * scale, wait * scale, 0.2

    rekey = clamp(rng.gauss(0.55 + 0.02 * f.pages, 0.15), 0.2, 2.0)
    completeness = clamp(rng.gauss(0.35, 0.10), 0.1, 0.8)
    if f.sent_back:
        chasing = clamp(rng.gauss(0.8, 0.25), 0.2, 1.8)
    else:
        chasing = clamp(rng.gauss(0.05, 0.03), 0.0, 0.2)
    addressable = rekey + completeness + chasing
    if addressable > 0.6 * f.analyst_hours:            # keep assessment at 40 percent of the file or more
        s = 0.6 * f.analyst_hours / addressable
        rekey, completeness, chasing = rekey * s, completeness * s, chasing * s
    assessment = f.analyst_hours - rekey - completeness - chasing

    incomplete = not (f.has_pan and f.has_address_proof and f.has_income_proof and f.has_photo)
    slipped = incomplete and not f.sent_back
    p_withdraw = 0.02 + 0.012 * max(0.0, f.turnaround_days - 5.0)
    roll = rng.random()
    if roll < p_withdraw:
        outcome = "withdrawn"
    elif roll < p_withdraw + 0.16:
        outcome = "rejected"
    else:
        outcome = "sanctioned"
    return HandCount(
        f.file_id, f.branch, f.product, f.channel, size, sampled, f.turnaround_days,
        round(transit, 2), round(queue, 2), round(work, 2), round(wait, 2),
        f.analyst_hours, round(rekey, 2), round(completeness, 2), round(chasing, 2), round(assessment, 2),
        f.sent_back, incomplete, slipped, outcome,
    )


def draw_sample(frame: list) -> tuple[list[HandCount], dict[Key, int], dict[Key, list]]:
    strata: dict[Key, list] = defaultdict(list)
    for f in frame:
        strata[(f.branch, f.product)].append(f)
    alloc = allocate(strata, SAMPLE_SIZE, MIN_PER_STRATUM)
    draw_rng = random.Random(SAMPLE_SEED)
    hc_rng = random.Random(HAND_COUNT_SEED)
    sample: list[HandCount] = []
    for key in sorted(strata):
        chosen = draw_rng.sample(strata[key], alloc[key])
        for f in sorted(chosen, key=lambda x: x.file_id):
            sample.append(hand_count(f, len(strata[key]), alloc[key], hc_rng))
    return sample, alloc, strata


# =============================================================================================
# 3. estimates with confidence intervals
# =============================================================================================

Value = Callable[[HandCount], float]
Estimate = tuple[float, float, float]      # point, low, high


def by_stratum(sample: list[HandCount]) -> dict[Key, list[HandCount]]:
    out: dict[Key, list[HandCount]] = defaultdict(list)
    for h in sample:
        out[(h.branch, h.product)].append(h)
    return out


def strat_mean(sample: list[HandCount], value: Value) -> Estimate:
    """Stratified mean (or proportion) with a normal 95 percent interval and the finite population correction."""
    groups = by_stratum(sample)
    big_n = sum(g[0].stratum_size for g in groups.values())
    est, var = 0.0, 0.0
    for g in groups.values():
        w = g[0].stratum_size / big_n
        ys = [float(value(h)) for h in g]
        est += w * statistics.fmean(ys)
        if len(ys) > 1:
            fpc = 1 - len(ys) / g[0].stratum_size
            var += w * w * fpc * statistics.variance(ys) / len(ys)
    se = math.sqrt(var)
    return est, max(0.0, est - Z95 * se), est + Z95 * se


def weighted_median(pairs: list[tuple[float, float]]) -> float:
    pairs = sorted(pairs)
    half = sum(w for _, w in pairs) / 2
    run = 0.0
    for v, w in pairs:
        run += w
        if run >= half:
            return v
    return pairs[-1][0]


def strat_median(sample: list[HandCount], value: Value, rng: random.Random) -> Estimate:
    """Weighted median with a stratified bootstrap: resample within each stratum, 2,000 times."""
    groups = by_stratum(sample)
    point = weighted_median([(value(h), h.weight) for h in sample])
    reps = []
    for _ in range(BOOTSTRAP_REPS):
        pairs = [(value(h), h.weight) for g in groups.values() for h in rng.choices(g, k=len(g))]
        reps.append(weighted_median(pairs))
    reps.sort()
    return point, reps[int(0.025 * BOOTSTRAP_REPS)], reps[int(0.975 * BOOTSTRAP_REPS) - 1]


def srs_median(values: list[float], rng: random.Random) -> Estimate:
    reps = sorted(statistics.median(rng.choices(values, k=len(values))) for _ in range(BOOTSTRAP_REPS))
    return statistics.median(values), reps[int(0.025 * BOOTSTRAP_REPS)], reps[int(0.975 * BOOTSTRAP_REPS) - 1]


