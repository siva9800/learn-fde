def load_day7() -> ModuleType:
    """Import Day 7's generator by path; registered in sys.modules so its dataclasses resolve."""
    spec = importlib.util.spec_from_file_location("inputs_inventory", DAY7_GENERATOR)
    if spec is None or spec.loader is None:
        raise SystemExit(f"cannot find Day 7's generator at {DAY7_GENERATOR}")
    module = importlib.util.module_from_spec(spec)
    sys.modules["inputs_inventory"] = module
    spec.loader.exec_module(module)
    return module


def frame_matches_day7(frame: list) -> str:
    """The first 200 frame rows are Day 7's sample: same seed, same draws, same order."""
    if not DAY7_SAMPLE.exists():
        return "Day 7's CSV not found; run Day 7's script to compare"
    with DAY7_SAMPLE.open(encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    same = all(r["file_id"] == f.file_id and float(r["turnaround_days"]) == f.turnaround_days
               for r, f in zip(rows, frame))
    return f"first {len(rows)} frame rows identical to Day 7's sample: {'yes' if same else 'NO'}"


