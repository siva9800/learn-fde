def loaded_cost_per_year() -> float:
    return sum(r for _, r, counted, _ in LOADED_COST_LINES if counted)


def queue_factor(rho: float) -> float:
    """Kingman's rho / (1 - rho): the part of waiting that explodes as utilisation nears one."""
    rho = min(rho, 0.995)
    return rho / (1 - rho)


@dataclass
class Baseline:
    hours_per_file: float
    addressable_hours: float
    queue_days: float
    median_turnaround: float
    walkaway_rate: float
    approval_rate: float
    sample: list[HandCount]


@dataclass
class Assumptions:
    loaded_cost: float
    capture: float = CAPTURE_SHARE
    contribution: float = CONTRIBUTION_PER_LOAN
    walkaway_kept_per_day: float = WALKAWAY_KEPT_PER_DAY
    cloud: float = CLOUD_PER_YEAR
    growth: float = GROWTH_NEXT_YEAR
    hires: int = HIRES_PLANNED


def utilisation_today(b: Baseline) -> float:
    return FILES_PER_MONTH * 12 * b.hours_per_file / (ANALYSTS * PRODUCTIVE_HOURS_PER_YEAR)


def hires_needed_without_system(b: Baseline, a: Assumptions) -> float:
    """Analysts to add next year to keep today's utilisation (and today's queue) at the new volume."""
    files_next = FILES_PER_MONTH * 12 * (1 + a.growth)
    return files_next * b.hours_per_file / (PRODUCTIVE_HOURS_PER_YEAR * utilisation_today(b)) - ANALYSTS


def after_system(b: Baseline, a: Assumptions) -> dict[str, float]:
    """Next year with the system and `a.hires` hires: utilisation, queue, turnaround and value."""
    rho0 = utilisation_today(b)
    files_next = FILES_PER_MONTH * 12 * (1 + a.growth)
    hours_after = b.hours_per_file - a.capture * b.addressable_hours
    rho = files_next * hours_after / ((ANALYSTS + a.hires) * PRODUCTIVE_HOURS_PER_YEAR)
    queue = b.queue_days * queue_factor(rho) / queue_factor(rho0)
    # day-one detection: the branch's wait runs in parallel with the queue instead of after it
    new_t = [h.transit_days + max(queue, h.branch_wait_days) + WORK_STAGE_AFTER_DAYS for h in b.sample]
    new_median = weighted_median([(t, h.weight) for t, h in zip(new_t, b.sample)])
    days_cut = max(0.0, b.median_turnaround - new_median)
    hires_avoided = max(0.0, hires_needed_without_system(b, a) - a.hires)
    capacity_cash = hires_avoided * a.loaded_cost
    kept_share = min(1.0, a.walkaway_kept_per_day * days_cut)
    loans_kept = files_next * b.walkaway_rate * kept_share * b.approval_rate
    retention = loans_kept * a.contribution
    run_cost = SUBSCRIPTION_PER_YEAR + a.cloud + STAFF_TIME_PER_YEAR
    return {
        "rho0": rho0, "rho": rho, "queue": queue, "median_after": new_median, "days_cut": days_cut,
        "hires_avoided": hires_avoided, "capacity_cash": capacity_cash, "loans_kept_pm": loans_kept / 12,
        "retention": retention, "run_cost": run_cost, "net": capacity_cash + retention - run_cost,
        "breakeven_loans_pm": max(0.0, (run_cost - capacity_cash) / a.contribution / 12),
        "sanctioned_pm": files_next * (1 - b.walkaway_rate) * b.approval_rate / 12,
    }


def lakh(x: float) -> str:
    return f"{x / LAKH:7.1f}"


def interval(e: Estimate, fmt: str) -> str:
    return f"{fmt.format(e[1])} to {fmt.format(e[2])}"


