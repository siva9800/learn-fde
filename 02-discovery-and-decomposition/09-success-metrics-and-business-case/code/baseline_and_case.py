def main() -> None:
    day7 = load_day7()
    frame = day7.make_loan_files(FRAME_SIZE, random.Random(day7.SEED))
    print("== 1. The sampling frame ==")
    print(f"{len(frame)} new files received in the two-week window (Day 7's generator, seed {day7.SEED})")
    print(frame_matches_day7(frame))

    sample, alloc, strata = draw_sample(frame)
    print()
    print("== 2. The stratified draw ==")
    print(f"strata: {len(strata)} (6 branch clusters x 4 products); sample {len(sample)}; "
          f"at least {MIN_PER_STRATUM} per stratum; seed {SAMPLE_SEED}")
    products = list(day7.PRODUCTS)
    print(f"{'frame / sampled':24s}" + "".join(f"{p:>16s}" for p in products))
    for br in sorted({k[0] for k in strata}):
        print(f"{br:24s}" + "".join(f"{len(strata[(br, p)]):>11d} / {alloc[(br, p)]:<2d}" for p in products).rstrip())

    rng = random.Random(SAMPLE_SEED + 1)
    med = strat_median(sample, lambda h: h.turnaround_days, rng)
    hours = strat_mean(sample, lambda h: h.analyst_hours)
    sendback = strat_mean(sample, lambda h: h.sent_back)
    print()
    print("== 3. The baseline against the ops report (95 percent intervals) ==")
    print(f"{'metric':28s}{'ops report':>11s}{'hand count':>12s}{'interval':>16s}   report inside?")
    for name, est, fmt in [("median turnaround, days", med, "{:.1f}"),
                           ("analyst hours per file", hours, "{:.1f}"),
                           ("send-back rate", sendback, "{:.0%}")]:
        rep = OPS_REPORT[name]
        inside = "yes" if est[1] <= rep <= est[2] else "no"
        print(f"{name:28s}{fmt.format(rep):>11s}{fmt.format(est[0]):>12s}{interval(est, fmt):>16s}   {inside}")

    addressable = strat_mean(sample, lambda h: h.addressable_hours)
    slip = strat_mean(sample, lambda h: h.slipped)
    walk = strat_mean(sample, lambda h: h.outcome == "withdrawn")
    decided = [h for h in sample if h.outcome != "withdrawn"]
    approval = sum(h.weight for h in decided if h.outcome == "sanctioned") / sum(h.weight for h in decided)
    incomplete_w = sum(h.weight for h in sample if h.incomplete)
    caught_w = sum(h.weight for h in sample if h.incomplete and h.sent_back)
    print()
    print("What the report never had (hand count only):")
    for name, est, fmt in [("addressable hours per file", addressable, "{:.2f}"),
                           ("decided with a document missing", slip, "{:.1%}"),
                           ("withdrawn by the customer", walk, "{:.1%}")]:
        print(f"  {name:36s}{fmt.format(est[0]):>7s}   ({interval(est, fmt)})")
    recall_label = "recall of today's human check"
    print(f"  {recall_label:36s}{caught_w / incomplete_w:>7.0%}   (incomplete files that were sent back)")
    print(f"  {'approval rate among decided files':36s}{approval:>7.0%}")

    print()
    print("Where the days go (weighted means, days):")
    for name, fn in [("transit: signed -> on SFTP", lambda h: h.transit_days),
                     ("queue: on SFTP -> first opened", lambda h: h.queue_days),
                     ("work: opened -> decision", lambda h: h.work_days),
                     ("branch wait (zero if not sent back)", lambda h: h.branch_wait_days)]:
        est = strat_mean(sample, fn)
        print(f"  {name:38s}{est[0]:5.1f}   ({interval(est, '{:.1f}')})")
    print("Where the hours go (weighted means, hours per file):")
    for name, fn in [("re-keying into the core", lambda h: h.rekey_hours),
                     ("completeness check", lambda h: h.completeness_hours),
                     ("chasing the branch", lambda h: h.chasing_hours),
                     ("credit assessment and memo", lambda h: h.assessment_hours)]:
        est = strat_mean(sample, fn)
        print(f"  {name:38s}{est[0]:5.2f}   ({interval(est, '{:.2f}')})")

    print()
    print("Why one number is not a baseline yet:")
    small = random.Random(20).sample([f.turnaround_days for f in frame], 20)
    m = srs_median(small, rng)
    print(f"  20 files picked at random            median {m[0]:.1f} days, interval {interval(m, '{:.1f}')}")
    print(f"  120 files, stratified                median {med[0]:.1f} days, interval {interval(med, '{:.1f}')}")
    clean = [f for f in frame if f.channel == "sftp_scan" and f.product == "two-wheeler"]
    print(f"  all 700 files in the frame           send-back rate {sum(f.sent_back for f in frame) / len(frame):.0%}")
    print(f"  two-wheeler SFTP scans only (n={len(clean)})  send-back rate {sum(f.sent_back for f in clean) / len(clean):.0%}"
          "  <- a pilot chosen this way flatters any tool")

    # ---- rupees ------------------------------------------------------------------------------
    print()
    print("== 4. Hours into rupees: the loaded cost of one analyst, per year ==")
    for line, rupees, counted, why in LOADED_COST_LINES:
        mark = "counted" if counted else "NOT counted"
        print(f"  {line:46s}{rupees / LAKH:6.2f} lakh  {mark:12s}{why}")
    loaded = loaded_cost_per_year()
    rate = loaded / PRODUCTIVE_HOURS_PER_YEAR
    print(f"  loaded {loaded / LAKH:.2f} lakh / {PRODUCTIVE_HOURS_PER_YEAR} productive hours = {rate:.0f} rupees an hour"
          f" (Day 4 placeholder {DAY4_PLANNING_RATE}; CTC alone gives {6.0 * LAKH / PRODUCTIVE_HOURS_PER_YEAR:.0f})")

    base = Baseline(hours_per_file=hours[0], addressable_hours=addressable[0],
                    queue_days=strat_mean(sample, lambda h: h.queue_days)[0], median_turnaround=med[0],
                    walkaway_rate=walk[0], approval_rate=approval, sample=sample)
    a = Assumptions(loaded_cost=loaded)
    problem_cost = FILES_PER_MONTH * 12 * base.addressable_hours * rate
    print(f"  the problem's cost:  {FILES_PER_MONTH * 12:,} files x {base.addressable_hours:.2f} h x {rate:.0f}"
          f" = {problem_cost / CRORE:.2f} crore a year   (Day 4's question: is it big enough?)")
    print(f"  the system's share at {CAPTURE_SHARE:.0%} capture: {problem_cost * CAPTURE_SHARE / CRORE:.2f} crore of capacity"
          "   (Day 9's question: how much, and is it cash?)")

    print()
    print("== 5. The capacity plan: the freed hours are spent once ==")
    need = hires_needed_without_system(base, a)
